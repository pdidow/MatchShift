const { chromium } = require('../../artifacts/browser/node_modules/playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
(async () => {
 const browser = await chromium.launch({channel:'msedge', headless:true});
 const context = await browser.newContext({viewport:{width:1440,height:1080}});
 const page = await context.newPage(); const errors=[];
 page.on('pageerror', e=>errors.push(e.message));
 const base=process.env.MATCHSHIFT_TEST_URL ?? 'http://localhost:5002';
 const session=require('node:crypto').randomUUID();
 const query=`session=${session}&lang=en&mode=Analyst`;
 const post=async (path,data)=>{ const r=await context.request.post(`${base}/api/demo/${path}?session=${session}`,{data}); assert(r.ok(), await r.text()); };
 await post('reset',{matchId:'MS-FLAGSHIP-001'}); await post('seek',{minute:63});
 await page.goto(`${base}/?${query}`,{waitUntil:'domcontentloaded'});
 await page.locator('.card').first().waitFor(); await page.locator('.splash').waitFor({state:'hidden'});
 await page.waitForFunction(()=>document.querySelector('.narrative-source')?.textContent.includes('Mock'));
 await page.screenshot({path:'artifacts/browser/analyst.png',fullPage:true});
 const snapshot=await (await context.request.get(`${base}/api/demo/state?${query}`)).json();
 const shift=snapshot.insights.find(i=>i.type==='ATTACK_CHANNEL_SHIFT'); assert(shift);
 const trace=await (await context.request.get(`${base}/api/demo/insights/${shift.id}/agents?${query}`)).json();
 assert.equal(trace.narrative.source,'mock'); assert.equal(trace.evidenceAudit.approved,true);
 const ready=await (await context.request.get(`${base}/api/demo/state?${query}`)).json();
 assert.equal(ready.insights.find(i=>i.id===shift.id).narrative.headline,trace.narrative.headline);
 await page.locator('.card').filter({hasText:'Westhaven attacks down the right'}).first().locator('button').filter({hasText:'WHY'}).click();
 await page.screenshot({path:'artifacts/browser/why.png',fullPage:true});
 await page.goto(`${base}/?session=${session}&lang=en&mode=MyTeam&team=WHA&player=WHA-17`,{waitUntil:'domcontentloaded'});
 await page.locator('.player-panel').waitFor(); await page.locator('.splash').waitFor({state:'hidden'}); assert((await page.locator('.player-panel').innerText()).includes('Since kick-off'));
 await page.screenshot({path:'artifacts/browser/player.png',fullPage:true});
 await page.goto(`${base}/?session=${session}&lang=fr&mode=TeachMe`,{waitUntil:'domcontentloaded'});
 await page.locator('.card-teach').first().waitFor();
 assert.equal(await page.locator('html').getAttribute('lang'),'fr');
 await page.goto(`${base}/broadcast?session=${session}&lang=en`,{waitUntil:'domcontentloaded'});
 await page.locator('.broadcast-overlay').waitFor();
 await page.waitForFunction(()=>document.querySelector('.broadcast-overlay')?.textContent.includes('Mock'));
 await page.screenshot({path:'artifacts/browser/broadcast.png',fullPage:true});
 await page.goto(`${base}/overlay?session=${session}&lang=en`,{waitUntil:'domcontentloaded'});
 await page.locator('.broadcast-overlay').waitFor();
 assert.equal(await page.locator('body').evaluate(e=>getComputedStyle(e).backgroundColor),'rgba(0, 0, 0, 0)');
 await context.setOffline(true); await page.locator('.broadcast-overlay').waitFor({state:'detached',timeout:18000});
 await context.setOffline(false); await page.locator('.broadcast-overlay').waitFor(); assert.equal(await page.locator('.broadcast-overlay').count(),1);
 await post('seek',{minute:0}); await page.locator('.broadcast-overlay').waitFor({state:'detached'});
 await post('seek',{minute:90});
 const recap=await (await context.request.get(`${base}/api/demo/recap/fulltime?session=${session}&lang=en&style=Broadcast`)).json();
 assert.equal(recap.narrative.source,'mock'); assert(JSON.stringify(recap.narrative).includes('2-2'));
 const independent=await browser.newContext();
 const independentPage=await independent.newPage();
 await independentPage.goto(`${base}/?lang=en&mode=Analyst`,{waitUntil:'domcontentloaded'});
 await independentPage.locator('.clock').waitFor(); assert.equal(await independentPage.locator('.clock').innerText(),'00:00');
 assert.deepEqual(errors,[]);
 fs.writeFileSync('docs/validation/browser-smoke.json',JSON.stringify({provider:'mock',browser:'Microsoft Edge / Playwright',passed:true,checks:['live cards','shared trace narrative','WHY panel','player summary','French teaching','synthetic broadcast composition','transparent overlay','seek invalidation','disconnect clearing and reconnect','mock fulltime recap','independent browser session'],pageErrors:errors},null,2));
 await browser.close(); console.log('Browser smoke passed');
})().catch(e=>{console.error(e);process.exit(1)});
